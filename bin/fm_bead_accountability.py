#!/usr/bin/env python3
"""Board accountability and owner-authored ETA revisions.

Usage:
  fm_bead_accountability.py check --home HOME [--now RFC3339] [--no-notify]
  fm_bead_accountability.py eta --home HOME --id ID --owner OWNER
      --eta RFC3339 --reason TEXT [--now RFC3339]

config/beads-board selects the existing board. Unjoined homes do nothing.
The check uses readonly bd export/ready, never assigns, dispatches or runs work.
Only eta mutates a bead, after matching its single assignee. Metadata eta,
etaby and eta_history are authoritative; state contains observation/delivery
receipts only. Revision reasons are required, never generated by the check.
A missing or null eta is no current commitment, even with retained etaby/history.
Inbox notifications use the existing idempotent note/announce interface.
Register one check in the board's owning home; do not install copies in mates.
--no-notify reports findings without acknowledging notification delivery.
Checks stay inside a 25-second monotonic budget for the watcher's 30-second
check envelope; unnotified commitments remain pending for the next poll.
"""
import argparse
from datetime import datetime, timezone
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

TERMINAL = {"closed", "tombstone"}
PAUSED = {"parked", "deferred", "deprioritized", "snoozed", "consolidation"}
WAITS = {"parked", "deferred", "consolidation", "external", "approval"}
BLOCKING = {"blocks", "waits-for"}


def timestamp(value):
    if not isinstance(value, str) or not value:
        raise ValueError("timestamp must be a nonempty RFC3339 string")
    result = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if result.tzinfo is None:
        raise ValueError("timestamp requires an explicit timezone")
    return result.astimezone(timezone.utc)


def atomic_json(path, value):
    fd, temporary = tempfile.mkstemp(prefix=".accountability-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(value, stream, sort_keys=True)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        directory = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def board_command(board, *args, readonly=True, deadline=None):
    environment = {key: value for key, value in os.environ.items()
                   if not key.startswith(("BD_", "BEADS_", "GIT_CONFIG_"))}
    flags = ["--readonly", "--sandbox"] if readonly else []
    timeout = 60 if deadline is None else min(10, deadline - time.monotonic())
    if timeout <= 0:
        raise TimeoutError("accountability poll budget exhausted")
    result = subprocess.run(["bd", *flags, *args], cwd=board, env=environment,
                            capture_output=True, text=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError("bd " + args[0] + " failed: " + result.stderr.strip()[:300])
    return result.stdout


def configured_board(home):
    config = home / "config/beads-board"
    if not config.exists():
        return None
    if config.is_symlink() or not config.is_file():
        raise ValueError("config/beads-board must be a regular file")
    lines = config.read_text(encoding="utf-8").splitlines()
    if not lines or not lines[0].strip():
        return None
    board = Path(lines[0].strip()).expanduser().resolve()
    if not (board / ".beads").is_dir():
        raise ValueError("configured beads board is unavailable")
    return board


def read_board(board, deadline):
    rows = [json.loads(line) for line in
            board_command(board, "export", "--no-memories", deadline=deadline).splitlines() if line.strip()]
    ready = json.loads(board_command(board, "ready", "--limit", "0", "--json", deadline=deadline))
    if not isinstance(ready, list):
        raise ValueError("bd ready did not return an array")
    by_id = {}
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("id"), str):
            raise ValueError("invalid board row")
        if row["id"] in by_id:
            raise ValueError("duplicate board identity")
        by_id[row["id"]] = row
    return by_id, {row["id"] for row in ready}


def single_owner(row):
    owner = row.get("assignee")
    return owner if isinstance(owner, str) and re.fullmatch(r"[^\s,;|]+", owner) else None


def commitment(row):
    metadata = row.get("metadata") or {}
    if not isinstance(metadata, dict):
        raise ValueError("metadata must be an object")
    eta, author = metadata.get("eta"), metadata.get("etaby")
    if eta is None:
        return None
    deadline = timestamp(eta)
    if not isinstance(author, str) or not author or author != single_owner(row):
        raise ValueError("etaby must equal the single assignee")
    return {"eta": deadline.isoformat(), "etaby": author}


def person_wait(row):
    """A native blocked task waiting on a person has one dated follow-up."""
    metadata = row.get("metadata") or {}
    if not isinstance(metadata, dict):
        raise ValueError("metadata must be an object")
    if "waiting" not in (row.get("labels") or []):
        return None
    who = metadata.get("waitingon")
    if not isinstance(who, str) or not who.strip():
        raise ValueError("waiting tag requires metadata.waitingon")
    if row.get("status") != "blocked":
        raise ValueError("waiting tag requires native blocked status")
    due = timestamp(row.get("due_at")).isoformat()
    receipt = metadata.get("waiting_reply")
    reply_id = None
    if receipt is not None:
        if (not isinstance(receipt, dict) or not isinstance(receipt.get("id"), str)
                or not receipt["id"].strip() or not isinstance(receipt.get("waitingon"), str)
                or not receipt["waitingon"].strip()):
            raise ValueError("waiting_reply requires a reply id, waitingon and due_at")
        receipt_due = timestamp(receipt.get("due_at")).isoformat()
        if receipt["waitingon"].strip() == who.strip() and receipt_due == due:
            reply_id = receipt["id"]
    return dict(waitingon=who.strip(), due_at=due, reply_id=reply_id)


def paused(row, now):
    labels = set(row.get("labels") or [])
    metadata = row.get("metadata") or {}
    if not isinstance(metadata, dict):
        raise ValueError("metadata must be an object")
    wait = metadata.get("wait") or {}
    if not isinstance(wait, dict):
        raise ValueError("metadata.wait must be an object")
    reason = wait.get("reason")
    named = wait.get("kind") in WAITS and isinstance(reason, str) and bool(reason.strip())
    until = wait.get("until")
    if named and until:
        named = timestamp(until) > now
    deferred = row.get("defer_until")
    person = person_wait(row)
    pending_reply = person and not person["reply_id"] and timestamp(person["due_at"]) > now
    return (row.get("status") == "deferred" or bool(labels & PAUSED)
            or bool(deferred and timestamp(deferred) > now) or named or bool(pending_reply))


def ready_minutes(row, defaults):
    labels = row.get("labels") or []
    for label in labels:
        match = re.fullmatch(r"eta:(\d+)([mh])", label)
        if match:
            return int(match[1]) * (60 if match[2] == "h" else 1)
    for key in [*labels, row.get("issue_type")]:
        if key in defaults:
            return defaults[key]
    return 240


def analyze(rows, ready, now, defaults, previous):
    """Return findings and ready-observation state; never mutate board rows."""
    live = {key: row for key, row in rows.items() if row.get("status") not in TERMINAL}
    edges = {key: [] for key in live}
    findings, observations = [], {}
    for key, row in live.items():
        for dep in row.get("dependencies") or []:
            if (dep.get("type") or dep.get("dependency_type")) not in BLOCKING:
                continue
            target = dep.get("depends_on_id") or dep.get("id")
            if target in live:
                edges[key].append(target)
        owner = single_owner(row)
        if not owner:
            findings.append({"kind": "owner", "id": key,
                             "detail": "exactly one assignee is required"})
        try:
            waiting = paused(row, now)
            person = person_wait(row)
            current = commitment(row)
        except (TypeError, ValueError) as error:
            findings.append({"kind": "invalid", "id": key, "detail": str(error)})
            continue
        metadata = row.get("metadata") or {}
        wait = metadata.get("wait") or {}
        if row.get("status") == "blocked" and not edges[key] and not waiting and not person:
            findings.append({"kind": "blocker", "id": key,
                             "detail": "blocked task names no live dependency or explicit wait"})
        if wait and not waiting and not edges[key] and row.get("status") != "deferred":
            findings.append({"kind": "wait", "id": key,
                             "detail": "wait needs a kind, reason and unexpired deadline if dated"})
        human = "captain" in (row.get("labels") or []) or owner == "captain"
        if waiting or human or not owner:
            continue
        if person:
            trigger = "reply received" if person["reply_id"] else "follow-up date reached"
            findings.append({"kind": "follow-up", "id": key, "owner": owner,
                             "detail": trigger + "; owner must resume or revise the named wait",
                             "wait": {"waitingon": person["waitingon"], "due_at": person["due_at"]}})
            continue
        if current and timestamp(current["eta"]) < now:
            findings.append({"kind": "overdue", "id": key, "owner": owner,
                             "detail": "committed ETA " + current["eta"] + " has passed",
                             "commitment": current})
        if key in ready and row.get("status") == "open" and not edges[key]:
            anchor = previous.get(key) or row.get("updated_at") or row.get("created_at")
            start = timestamp(anchor)
            observations[key] = start.isoformat()
            if (now - start).total_seconds() >= 60 * ready_minutes(row, defaults):
                findings.append({"kind": "stalled-ready", "id": key, "owner": owner,
                                 "detail": "ready work has not advanced; owner must act or name a wait"})
    # Iterative DFS: a deep valid dependency chain must not overflow Python's stack.
    colors, cycles = {}, set()
    for root in sorted(edges):
        if colors.get(root):
            continue
        path, positions = [root], {root: 0}
        colors[root] = 1
        stack = [(root, iter(sorted(set(edges[root]))))]
        while stack:
            node, children = stack[-1]
            target = next(children, None)
            if target is None:
                colors[node] = 2
                stack.pop()
                positions.pop(node)
                path.pop()
            elif colors.get(target) == 1:
                cycle = path[positions[target]:]
                offset = min(range(len(cycle)), key=lambda index: cycle[index])
                canonical = tuple(cycle[offset:] + cycle[:offset])
                if canonical not in cycles:
                    cycles.add(canonical)
                    findings.append({"kind": "cycle", "id": canonical[0],
                                     "detail": " -> ".join((*canonical, canonical[0]))})
            elif not colors.get(target):
                colors[target] = 1
                positions[target] = len(path)
                path.append(target)
                stack.append((target, iter(sorted(set(edges[target])))))
    return findings, observations


def slip_commitments(row, now):
    """A notice identifies the missed commitment, not a mutable update timestamp."""
    current = commitment(row)
    result = []
    if current and timestamp(current["eta"]) < now:
        result.append(current)
    history = (row.get("metadata") or {}).get("eta_history") or []
    if not isinstance(history, list):
        raise ValueError("eta_history must be an array")
    for revision in history:
        prior = revision.get("previous")
        if prior and timestamp(prior["eta"]) < timestamp(revision["recorded_at"]):
            result.append(prior)
    return result


def notify(home, script, request_id, text, deadline):
    environment = dict(os.environ, FM_HOME=str(home))
    timeout = min(5, deadline - time.monotonic())
    if timeout <= 0:
        raise TimeoutError("Inbox notification remains pending for the next poll")
    result = subprocess.run(["bash", str(script), "note", "--request-id", request_id,
                             "--json", "-"], input=text, text=True, capture_output=True,
                            env=environment, timeout=timeout)
    if result.returncode == 3:
        receipt = json.loads(result.stdout)
        note_id = receipt.get("id") or (receipt.get("note") or {}).get("id")
        if not isinstance(note_id, str) or not note_id:
            raise RuntimeError("saved Inbox note has no usable receipt")
        timeout = min(5, deadline - time.monotonic())
        if timeout <= 0:
            raise TimeoutError("saved Inbox notification needs announcement on the next poll")
        result = subprocess.run(["bash", str(script), "announce", "--json", note_id],
                                text=True, capture_output=True, env=environment, timeout=timeout)
    if result.returncode:
        raise RuntimeError("Inbox delivery not acknowledged; retry keeps the same request ID")


def check(home, board, now, no_notify):
    deadline = time.monotonic() + 25
    state = home / "state"
    state.mkdir(mode=0o700, parents=True, exist_ok=True)
    marker = state / ".bead-accountability.json"
    lock = state / ".bead-accountability.lock"
    if state.is_symlink() or marker.is_symlink() or lock.is_symlink():
        raise ValueError("accountability state must not be symlinked")
    with lock.open("a", encoding="utf-8") as locked:
        os.chmod(lock, 0o600)
        fcntl.flock(locked, fcntl.LOCK_EX | fcntl.LOCK_NB)
        saved = json.loads(marker.read_text()) if marker.exists() else {}
        if saved.get("board") not in (None, str(board)):
            raise ValueError("accountability state belongs to another board")
        rows, ready = read_board(board, deadline)
        defaults = {}
        config = home / "config/bead-eta-defaults"
        if config.exists():
            for line in config.read_text().splitlines():
                key, separator, value = line.partition("=")
                if separator and value.strip().isdigit():
                    defaults[key.strip()] = int(value.strip())
        findings, observations = analyze(rows, ready, now, defaults, saved.get("ready", {}))
        reported = set(saved.get("reported", []))
        active = set()
        for finding in findings:
            event = ([finding["kind"], finding["id"], finding["wait"]]
                     if finding["kind"] == "follow-up" else finding)
            encoded = json.dumps(event, sort_keys=True)
            identity = hashlib.sha256(encoded.encode()).hexdigest()
            active.add(identity)
            if identity not in reported:
                owner = " (owner " + finding["owner"] + ")" if finding.get("owner") else ""
                print("bead-accountability: " + finding["kind"] + " " + finding["id"]
                      + owner + " - " + finding["detail"])
        notices = set(saved.get("notices", []))
        invalid = {finding["id"] for finding in findings if finding["kind"] == "invalid"}
        if not no_notify:
            for key, row in rows.items():
                if key in invalid or row.get("status") in TERMINAL or paused(row, now):
                    continue
                if single_owner(row) in (None, "captain") or "captain" in (row.get("labels") or []):
                    continue
                person = person_wait(row)
                events = ([{"kind": "waiting-follow-up", "waitingon": person["waitingon"],
                            "due_at": person["due_at"]}] if person else slip_commitments(row, now))
                for missed in events:
                    identity = hashlib.sha256(json.dumps(
                        [str(board), key, missed], sort_keys=True).encode()).hexdigest()
                    if identity in notices or time.monotonic() >= deadline - 0.25:
                        continue
                    if person:
                        text = ("Waiting follow-up " + key + ": " + single_owner(row)
                                + " must resurface the task once after the reply or due date. "
                                "Read the bead's waitingon/due_at/waiting_reply, then resume "
                                "or revise its wait and ETA. This authorizes no protected action.")
                        prefix = "bead-follow-up:"
                    else:
                        text = ("ETA slip " + key + ": " + missed["etaby"] + " committed "
                                + missed["eta"] + ". Read the bead's eta/etaby/eta_history for the "
                                "owner-authored reason and revised ETA; missing values are not resolved. "
                                "This notice authorizes no dispatch or protected action.")
                        prefix = "bead-eta:"
                    notify(home, Path(__file__).with_name("fm-inbox.sh"),
                           prefix + identity, text, deadline)
                    notices.add(identity)
                    # Save delivered notices without acknowledging a still-incomplete poll.
                    atomic_json(marker, dict(board=str(board), ready=observations,
                                             reported=sorted(reported), notices=sorted(notices)))
        atomic_json(marker, dict(board=str(board), ready=observations,
                                 reported=sorted(active), notices=sorted(notices)))


def record_eta(home, board, issue_id, owner, eta, reason, now):
    deadline = timestamp(eta)
    if deadline <= now:
        raise ValueError("new ETA must be in the future")
    if not reason.strip():
        raise ValueError("an owner-authored commitment/revision reason is required")
    state = home / "state"
    state.mkdir(mode=0o700, parents=True, exist_ok=True)
    lock = state / ".bead-accountability.lock"
    if state.is_symlink() or lock.is_symlink():
        raise ValueError("accountability state must not be symlinked")
    with lock.open("a", encoding="utf-8") as locked:
        os.chmod(lock, 0o600)
        fcntl.flock(locked, fcntl.LOCK_EX)
        rows = json.loads(board_command(board, "show", issue_id, "--json"))
        row = rows[0] if isinstance(rows, list) and len(rows) == 1 else None
        if row is None or row.get("id") != issue_id or row.get("status") in TERMINAL:
            raise ValueError("ETA requires one existing nonterminal bead")
        if single_owner(row) != owner:
            raise ValueError("only the bead's single assignee may commit its ETA")
        metadata = row.get("metadata") or {}
        previous = None
        if metadata.get("eta") is not None:
            # A reassigned task retains the previous owner's commitment in history.
            previous = {"eta": timestamp(metadata["eta"]).isoformat(),
                        "etaby": metadata.get("etaby")}
            if not isinstance(previous["etaby"], str) or not previous["etaby"]:
                raise ValueError("previous ETA has no committing owner; reconcile it first")
        history = metadata.get("eta_history") or []
        if not isinstance(history, list):
            raise ValueError("eta_history must be an array")
        current = {"eta": deadline.isoformat(), "etaby": owner}
        if previous == current:
            print(json.dumps(dict(id=issue_id, outcome="unchanged", **current)))
            return
        history = [*history, dict(**current, previous=previous,
                                 recorded_at=now.isoformat(), reason=reason.strip())]
        updated = dict(metadata, **current, eta_reason=reason.strip(), eta_history=history)
        board_command(board, "update", issue_id, "--metadata", json.dumps(updated), readonly=False)
        print(json.dumps(dict(id=issue_id, outcome="recorded", **current)))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    poll = commands.add_parser("check")
    poll.add_argument("--no-notify", action="store_true")
    record = commands.add_parser("eta")
    for name in ("id", "owner", "eta", "reason"):
        record.add_argument("--" + name, required=True)
    for command in (poll, record):
        command.add_argument("--home", required=True, type=Path)
        command.add_argument("--now", type=timestamp)
    args = parser.parse_args()
    try:
        home = args.home.resolve()
        board = configured_board(home)
        if board is None:
            if args.command == "eta":
                raise ValueError("ETA recording requires config/beads-board")
            return 0
        now = args.now or datetime.now(timezone.utc)
        if args.command == "check":
            check(home, board, now, args.no_notify)
        else:
            record_eta(home, board, args.id, args.owner, args.eta, args.reason, now)
    except (OSError, ValueError, TypeError, KeyError, RuntimeError, subprocess.SubprocessError) as error:
        print("bead-accountability: unavailable - " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
